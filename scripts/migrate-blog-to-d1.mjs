/**
 * Migrate static blogPostsData → D1 seed SQL + optional local JSON seed.
 *
 * Usage:
 *   node scripts/migrate-blog-to-d1.mjs
 *
 * Writes: scripts/blog-seed.sql
 * Then apply (after creating D1 + schema):
 *   npx wrangler d1 execute mernify-content --remote --file=functions/_lib/blog-schema.sql
 *   npx wrangler d1 execute mernify-content --remote --file=scripts/blog-seed.sql
 *
 * Local file store (Vite):
 *   Delete .data/blog-store.json and restart `npm run dev` to re-seed,
 *   or run: node scripts/migrate-blog-to-d1.mjs --local-store
 */

import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { randomUUID, createHash } from 'node:crypto'
import { blogPostsData } from '../src/content/blogPostsData.js'
import { postToRowFields } from '../functions/_lib/blogNormalize.js'
import { slugify } from '../functions/_lib/blogValidate.js'
import { createLocalStore, resolveRepoRoot } from '../functions/_lib/blogLocalStore.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')

const CATEGORIES = [
  'AI',
  'Web Development',
  'Cloud',
  'DevOps',
  'UI/UX',
  'Business',
  'Product Engineering',
  'SaaS',
  'MERN',
]

function sqlStr(value) {
  if (value == null) return 'NULL'
  return `'${String(value).replace(/'/g, "''")}'`
}

function sqlInt(value) {
  if (value == null || Number.isNaN(Number(value))) return 'NULL'
  return String(Math.trunc(Number(value)))
}

async function writeSeedSql() {
  const now = Date.now()
  const lines = [
    '-- Auto-generated by scripts/migrate-blog-to-d1.mjs',
    '-- Apply after functions/_lib/blog-schema.sql',
    'BEGIN TRANSACTION;',
    '',
    '-- Categories',
  ]

  const catRows = CATEGORIES.map((name, index) => ({
    id: randomUUID(),
    name,
    slug: slugify(name),
    sort_order: index,
    created_at: now,
  }))

  for (const c of catRows) {
    lines.push(
      `INSERT OR IGNORE INTO categories (id, name, slug, sort_order, created_at) VALUES (${sqlStr(c.id)}, ${sqlStr(c.name)}, ${sqlStr(c.slug)}, ${sqlInt(c.sort_order)}, ${sqlInt(c.created_at)});`,
    )
  }

  lines.push('', '-- Posts (status=published; preserve /assets/images/blog/… paths)', '')

  for (const post of blogPostsData) {
    const id = randomUUID()
    const fields = postToRowFields(post, {
      status: 'published',
      publishedBy: 'migration',
      nowTs: now,
    })
    lines.push(
      `INSERT OR REPLACE INTO posts (
  id, slug, title, excerpt, category, author_name, author_role,
  published_at, updated_at, reading_minutes, featured, image, image_alt, image_src_set,
  tags_json, sections_json, faq_json, status, seo_title, seo_description, seo_og_image,
  created_at, updated_at_ts, published_by
) VALUES (
  ${sqlStr(id)}, ${sqlStr(fields.slug)}, ${sqlStr(fields.title)}, ${sqlStr(fields.excerpt)},
  ${sqlStr(fields.category)}, ${sqlStr(fields.author_name)}, ${sqlStr(fields.author_role)},
  ${sqlStr(fields.published_at)}, ${sqlStr(fields.updated_at)}, ${sqlInt(fields.reading_minutes)},
  ${sqlInt(fields.featured)}, ${sqlStr(fields.image)}, ${sqlStr(fields.image_alt)}, ${sqlStr(fields.image_src_set)},
  ${sqlStr(fields.tags_json)}, ${sqlStr(fields.sections_json)}, ${sqlStr(fields.faq_json)},
  ${sqlStr(fields.status)}, ${sqlStr(fields.seo_title)}, ${sqlStr(fields.seo_description)}, ${sqlStr(fields.seo_og_image)},
  ${sqlInt(now)}, ${sqlInt(fields.updated_at_ts)}, ${sqlStr(fields.published_by)}
);`,
    )
  }

  lines.push('COMMIT;', '')

  const outPath = path.join(root, 'scripts', 'blog-seed.sql')
  await fs.writeFile(outPath, lines.join('\n'), 'utf8')
  return outPath
}

async function seedLocalStore() {
  const store = createLocalStore(resolveRepoRoot())
  const dataPath = store.storePath
  try {
    await fs.unlink(dataPath)
  } catch {
    /* missing is fine */
  }
  await store.ensureSeeded()
  const { posts } = await store.listAdmin({ limit: 500 })
  return { dataPath, count: posts.length }
}

function printInstructions(seedPath) {
  console.log(`
Mernify blog → D1 migration
===========================
Seed SQL written: ${seedPath}
Posts from blogPostsData: ${blogPostsData.length}

1) Create D1 (once):
   npx wrangler d1 create mernify-content
   # Copy the database_id into wrangler.toml [[d1_databases]]

2) Apply schema + seed (remote):
   npx wrangler d1 execute mernify-content --remote --file=functions/_lib/blog-schema.sql
   npx wrangler d1 execute mernify-content --remote --file=scripts/blog-seed.sql

3) Local D1 (optional):
   npx wrangler d1 execute mernify-content --local --file=functions/_lib/blog-schema.sql
   npx wrangler d1 execute mernify-content --local --file=scripts/blog-seed.sql

4) Vite local JSON store (no D1):
   node scripts/migrate-blog-to-d1.mjs --local-store
   # or delete .data/blog-store.json and restart npm run dev

Checksum: ${createHash('sha256').update(JSON.stringify(blogPostsData.map((p) => p.slug))).digest('hex').slice(0, 12)}
`)
}

const args = process.argv.slice(2)
const seedPath = await writeSeedSql()
printInstructions(seedPath)

if (args.includes('--local-store')) {
  const result = await seedLocalStore()
  console.log(`Local store seeded: ${result.count} posts → ${result.dataPath}`)
}
